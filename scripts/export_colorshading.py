"""Rebuild data-only RTL tables from the two independently captured flatfields."""
from pathlib import Path
import hashlib
import json
import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def main():
    assets = ROOT / 'calibration/colorshading'
    arrays = [np.load(assets / f'{name}_spatial_grid_float.npy')
              for name in ('indoor', 'daylight_assisted')]
    assert all(a.shape == (13, 17, 4) and np.isfinite(a).all() and (a > 0).all()
               for a in arrays)
    base = np.sqrt(arrays[0] * arrays[1])
    # Original calibration positions span 0..1279/719; hardware cells are 80x60.
    old_x, old_y = np.linspace(0, 1279, 17), np.linspace(0, 719, 13)
    target_x, target_y = np.arange(17)*80, np.arange(13)*60
    horizontal = np.empty_like(base)
    sampled = np.empty_like(base)
    for phase in range(4):
        for y in range(13):
            horizontal[y, :, phase] = np.interp(target_x, old_x, base[y, :, phase])
        for x in range(17):
            sampled[:, x, phase] = np.interp(target_y, old_y, horizontal[:, x, phase])
    q = np.floor(sampled*1024 + .5).astype(np.int64)
    assert q.min() > 0 and q.max() <= 4095
    out = ROOT / 'rtl/isp'
    out.mkdir(parents=True, exist_ok=True)
    lines = ['// Generated by scripts/export_colorshading.py; G0,R,B,G1; unsigned Q2.10.']
    for addr, row in enumerate(q.reshape(-1, 4)):
        word = sum(int(v) << shift for v, shift in zip(row, (36,24,12,0)))
        lines.append(f"8'd{addr}: grid_word = 48'h{word:012x};")
    (out/'colorshading_lut_case.vh').write_text('\n'.join(lines)+'\n', encoding='ascii')
    # Fixed unity-exposure sRGB encoding. No per-scene percentile normalization.
    x = np.arange(256)/255
    srgb = np.where(x <= .0031308, 12.92*x, 1.055*x**(1/2.4)-.055)
    tone = np.floor(srgb*255+.5).clip(0,255).astype(int)
    (out/'colorshading_gamma_case.vh').write_text(
        '// Fixed sRGB OETF, unity exposure.\n' + '\n'.join(
            f"8'd{i}: tone_value = 8'd{v};" for i,v in enumerate(tone))+'\n', encoding='ascii')
    np.save(assets/'base_grid_q10.npy', q.astype('uint16'))
    meta = {'bayer':'BGGR', 'phase_order':['G0','R','B','G1'],
            'phase_coordinates':{'G0':[0,1], 'R':[1,1], 'B':[0,0], 'G1':[1,0]},
            'black_level':67, 'cell_size':[80,60], 'grid_shape':[13,17,4],
            'q10_min_max':[int(q.min()),int(q.max())],
            'spatial_policy':'geometric mean of two normalized calibration maps, no scene fitting',
            'tone':'fixed unity-exposure sRGB OETF; unlike Python percentile rendering',
            'sources':{p.name:hashlib.sha256(p.read_bytes()).hexdigest()
                       for p in sorted(assets.glob('*_spatial_grid_float.npy'))}}
    (assets/'hardware_profile.json').write_text(json.dumps(meta,indent=2)+'\n', encoding='utf-8')
    print(json.dumps(meta,indent=2))


if __name__ == '__main__':
    main()
