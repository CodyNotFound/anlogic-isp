"""Losslessly pack canonical int32 biases and 0..31 shifts into LUTRAM.
Biases: low16 plus sparse upper-word corrections; shifts: dense 3-bit window
plus sparse literal exceptions. No quantization, changed scales or new cycles.
Run after model import; --check refuses stale derived HDL/ROM files.
"""
import argparse,hashlib,json
from pathlib import Path

def generate(root):
    folder=root/'rtl/analytics/face_cnn'
    for i,line in enumerate((folder/'program.hex').read_text(encoding='ascii').split()):
        word=int(line,16);ci=(word>>87)&127;co=(word>>94)&127
        src=(word>>4)&131071;src2=(word>>21)&131071;dst=(word>>38)&131071
        if ci not in (1,4,16,32,64) or co not in (1,4,16,32,64) or src%ci or src2%ci or dst%co or ((word&15)!=1 and ci!=co):
            raise ValueError(f'Operation {i}: aligned power-of-two channel address contract violated')
    bias=[int(x,16) for x in (folder/'bias.hex').read_text(encoding='ascii').split()]
    shift=[int(x,16) for x in (folder/'shift.hex').read_text(encoding='ascii').split()]
    if len(bias)!=len(shift) or not bias or len(bias)>1524:raise ValueError('Bias/shift depth contract violated')
    if any(v<0 or v>0xffffffff for v in bias):raise ValueError('Bias must be int32 bit patterns')
    if any(v<0 or v>31 for v in shift):raise ValueError('Shift must be 0..31')
    base=max(range(25),key=lambda b:sum(b<=s<b+8 for s in shift))
    be=[];se=[]
    for i,v in enumerate(bias):
        high=v>>16;sign=65535 if v&32768 else 0
        if high!=sign:be.append((i,high))
    for i,s in enumerate(shift):
        if not base<=s<base+8:se.append((i,s))
    if len(be)>64:raise ValueError('Sparse bias exception budget exceeded; review ROM mapping')
    bits=3
    if len(se)>64:base=0;se=[];bits=5
    # Pad only unused capacity. Canonical inputs remain the source of truth.
    bp=bias+[0]*(1524-len(bias));sp=shift+[base]*(1524-len(shift))
    btext=''.join(f'{v&65535:04x}\n' for v in bp)
    stext=''.join(format((v-base)&((1<<bits)-1),'0'+str((bits+3)//4)+'x')+'\n' for v in sp)
    lines=[f'localparam integer MODEL_SHIFT_BITS={bits};','// Generated by scripts/pack_yunet_rom.py; canonical bias.hex/shift.hex remain authoritative.',
           'function signed [31:0] unpack_model_bias;',
           'input [10:0] addr; input [15:0] low; reg [15:0] high;',
           'begin case(addr)']
    lines += [f"11'd{i}: high=16'h{v:04x};" for i,v in be]
    lines += ['default: high={16{low[15]}};','endcase unpack_model_bias={high,low}; end','endfunction',
              'function signed [6:0] unpack_model_shift;','input [10:0] addr; input [MODEL_SHIFT_BITS-1:0] code;',
              'begin case(addr)']
    lines += [f"11'd{i}: unpack_model_shift=7'd{v};" for i,v in se]
    lines += [f"default: unpack_model_shift=7'd{base}+{{{{(7-MODEL_SHIFT_BITS){{1'b0}}}},code}};",'endcase end','endfunction']
    header='\n'.join(lines)+'\n'
    # Independently reconstruct EVERY canonical entry before producing artifacts.
    bh=dict(be);sh=dict(se)
    for i,(b,s) in enumerate(zip(bias,shift)):
        lo=int(btext.splitlines()[i],16)
        actual=(bh.get(i,65535 if lo&32768 else 0)<<16)|lo
        code=int(stext.splitlines()[i],16)
        if actual!=b or sh.get(i,base+code)!=s:raise AssertionError('Packing changed model value')
    files={'bias.hex.lo16':btext,'shift.hex.packed':stext,'yunet_rom_unpack.vh':header}
    report=dict(entries=len(bias),bias_exceptions=len(be),shift_exceptions=len(se),shift_base=base,shift_bits=bits,
                bias_sha256=hashlib.sha256((folder/'bias.hex').read_bytes()).hexdigest(),
                shift_sha256=hashlib.sha256((folder/'shift.hex').read_bytes()).hexdigest())
    return folder,files,report

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1]);ap.add_argument('--check',action='store_true')
    a=ap.parse_args();folder,files,report=generate(a.root)
    if a.check:
        for name,data in files.items():
            p=folder/name
            if not p.is_file() or p.read_bytes()!=data.encode('ascii'):
                raise SystemExit('Stale packed model: run scripts/pack_yunet_rom.py: '+str(p))
    else:
        for name,data in files.items():(folder/name).write_bytes(data.encode('ascii'))
    print(json.dumps(dict(status='checked' if a.check else 'generated',**report)))

if __name__=='__main__':main()
